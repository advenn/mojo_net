"""Generate src/json/ryu_tables.mojo: the powers of five that Ryū's
double-to-shortest conversion multiplies by (Ulf Adams, "Ryū: fast
float-to-string conversion", PLDI 2018; d2s.c in github.com/ulfjack/ryu);
and src/json/lemire_tables.mojo, those the Eisel-Lemire decimal-to-double
algorithm multiplies by (`json.number`; Daniel Lemire, "Number Parsing at
a Gigabyte per Second", 2021; fast_float's table_generation.py).

Each entry is a 128-bit integer, stored as two UInt64 words, low word
first, in one flat Array (entry i at [2*i] and [2*i + 1]), so that one
lookup touches one cache line:

  POW5_INV_SPLIT[q] = floor(2^(bitlen(5^q) - 1 + 125) / 5^q) + 1,  q in [0, 342)
  POW5_SPLIT[i]     = 5^i scaled to exactly 125 bits (shifted left while
                      shorter, right, truncating, while longer), i in [0, 326)
  POW5_128[q]       = 5^q in 128 bits, for q in [-342, 308]: for q >= 0,
                      scaled to [2^127, 2^128), truncated; for q < 0, its
                      reciprocal 2^b / 5^-q, rounded up and scaled likewise
                      (b = bitlen(5^-q) + 127 down to q = -27, else twice
                      bitlen(5^-q) + 128, truncated), stored high word first

The values come from Python's integers, never from a copied table, and
each one is checked against its definition before it is written.

  gen_ryu_tables.py --write   regenerate both files
  gen_ryu_tables.py --check   fail if the committed file differs (CI)
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "json", "ryu_tables.mojo")
LEMIRE_OUT = os.path.join(ROOT, "src", "json", "lemire_tables.mojo")
LEMIRE_MIN_Q = -342
LEMIRE_MAX_Q = 308

POW5_INV_BITCOUNT = 125
POW5_BITCOUNT = 125
POW5_INV_TABLE_SIZE = 342
POW5_TABLE_SIZE = 326
MASK64 = (1 << 64) - 1


def pow5_inv(q):
    p = 5**q
    j = p.bit_length() - 1 + POW5_INV_BITCOUNT
    v = (1 << j) // p + 1
    # The definition, checked: v is the smallest integer with v * 5^q > 2^j
    # (strictly, since 5^q is odd for q > 0 and 2^j / 1 + 1 for q = 0).
    assert v * p > (1 << j) and (v - 1) * p <= (1 << j)
    assert v.bit_length() <= 128
    return v


def pow5(i):
    p = 5**i
    n = p.bit_length()
    v = p << (POW5_BITCOUNT - n) if n < POW5_BITCOUNT else p >> (n - POW5_BITCOUNT)
    assert v.bit_length() == POW5_BITCOUNT
    # Truncation, checked: v * 2^(n - 125) <= 5^i < (v + 1) * 2^(n - 125).
    if n >= POW5_BITCOUNT:
        s = n - POW5_BITCOUNT
        assert (v << s) <= p < ((v + 1) << s)
    else:
        assert v == p << (POW5_BITCOUNT - n)
    return v


def pow5_128(q):
    """fast_float's power_of_five_128 entry for 5^q."""
    if q >= 0:
        p = 5**q
        v = p
        while v < (1 << 127):
            v *= 2
        while v >= (1 << 128):
            v //= 2
        # Checked: v is 5^q times a power of two, truncated.
        n = p.bit_length()
        if n > 128:
            assert (v << (n - 128)) <= p < ((v + 1) << (n - 128))
        else:
            assert v == p << (128 - n)
    else:
        p = 5**-q
        z = p.bit_length()  # (the least z with 2^z >= 5^-q: 5^-q is no power of two)
        assert (1 << (z - 1)) < p <= (1 << z)
        b = z + 127 if q >= -27 else 2 * z + 128
        c = (1 << b) // p + 1
        # Checked: c is the least integer above 2^b / 5^-q,
        assert c * p > (1 << b) and (c - 1) * p <= (1 << b)
        v = c
        while v >= (1 << 128):
            v //= 2
        # and v is c truncated to 128 bits (only below q = -27).
        s = c.bit_length() - v.bit_length()
        assert (v << s) <= c < ((v + 1) << s) and (s == 0 or q < -27)
    assert (1 << 127) <= v < (1 << 128)
    return v


def lemire_render():
    words = []
    for q in range(LEMIRE_MIN_Q, LEMIRE_MAX_Q + 1):
        v = pow5_128(q)
        words.append(v >> 64)
        words.append(v & MASK64)
    n = LEMIRE_MAX_Q - LEMIRE_MIN_Q + 1
    lines = [
        '"""The powers of five that `json.number`\'s Eisel-Lemire algorithm',
        "multiplies by: 5^q in 128 bits for q in [-342, 308], two UInt64 words",
        "per entry, the high word first (fast_float's power_of_five_128).",
        "",
        "Generated by tools/gen_ryu_tables.py from Python's integers; do not edit",
        '(`pixi run gen-json` regenerates, and CI checks it is current)."""',
        "",
        f"comptime POW5_128_MIN_Q = {LEMIRE_MIN_Q}",
        f"comptime POW5_128_MAX_Q = {LEMIRE_MAX_Q}",
        "",
        f"comptime POW5_128: Array[UInt64, {2 * n}] = [",
    ]
    for i in range(0, len(words), 4):
        lines.append("    " + " ".join(f"{w}," for w in words[i : i + 4]))
    lines.append("]")
    return "\n".join(lines) + "\n"


def table(name, size, entry, doc):
    words = []
    for i in range(size):
        v = entry(i)
        words.append(v & MASK64)
        words.append(v >> 64)
    lines = [f"comptime {name}: Array[UInt64, {2 * size}] = ["]
    for i in range(0, len(words), 4):
        lines.append("    " + " ".join(f"{w}," for w in words[i : i + 4]))
    lines.append("]")
    lines.append(f'"""{doc}"""')
    return "\n".join(lines)


def render():
    head = '''"""Ryū's tables of powers of five (`json.ryu`), as 128-bit integers:
two UInt64 words per entry, the low word first.

Generated by tools/gen_ryu_tables.py from Python's integers; do not edit
(`pixi run gen-json` regenerates, and CI checks it is current)."""

comptime POW5_INV_BITCOUNT = 125
comptime POW5_BITCOUNT = 125
comptime POW5_INV_TABLE_SIZE = 342
comptime POW5_TABLE_SIZE = 326

'''
    inv = table(
        "POW5_INV_SPLIT",
        POW5_INV_TABLE_SIZE,
        pow5_inv,
        "floor(2^(bitlen(5^q) - 1 + 125) / 5^q) + 1, for q in [0, 342).",
    )
    fwd = table(
        "POW5_SPLIT",
        POW5_TABLE_SIZE,
        pow5,
        "5^i scaled to 125 bits (truncated), for i in [0, 326).",
    )
    return head + inv + "\n\n" + fwd + "\n"


def main():
    if len(sys.argv) != 2 or sys.argv[1] not in ("--write", "--check"):
        sys.exit(__doc__)
    for out, text in ((OUT, render()), (LEMIRE_OUT, lemire_render())):
        if sys.argv[1] == "--write":
            with open(out, "w") as f:
                f.write(text)
            print(f"wrote {os.path.relpath(out, ROOT)}")
            continue
        try:
            with open(out) as f:
                have = f.read()
        except FileNotFoundError:
            sys.exit(f"{os.path.relpath(out, ROOT)} is missing: run pixi run gen-json")
        if have != text:
            sys.exit(f"{os.path.relpath(out, ROOT)} is stale: run pixi run gen-json")
    if sys.argv[1] == "--check":
        print("json: Ryū and Eisel-Lemire tables current")


if __name__ == "__main__":
    main()
