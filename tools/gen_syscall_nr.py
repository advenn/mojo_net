#!/usr/bin/env python3
"""Generate src/linux/nr.mojo from the kernel uapi headers.

x86_64 numbers come from <asm/unistd_64.h>. aarch64 uses the generic table
(<asm-generic/unistd.h>) with the defines arm64's <asm/unistd.h> sets.
Every syscall in WANTED must exist on both architectures; the script fails
otherwise, so the library can never reference a syscall missing on one arch
(aarch64 has no poll, epoll_wait, accept, pipe, open, ...).
"""

import os
import re
import subprocess
import sys

WANTED = [
    # process / misc
    "getpid", "gettid", "getuid", "geteuid", "getgid", "getegid",
    "exit_group", "uname", "getrandom", "prlimit64", "getcpu",
    "sched_getaffinity", "sched_setaffinity", "sched_yield", "kill", "tgkill",
    # processes (the server's workers)
    "execve", "clone3", "clone", "waitid", "pidfd_send_signal",
    # signals
    "rt_sigprocmask", "rt_sigaction", "signalfd4",
    # time
    "clock_gettime", "clock_nanosleep", "timerfd_create", "timerfd_settime",
    "timer_create", "timer_settime", "timer_delete",
    # files / fds
    "openat", "read", "write", "readv", "writev", "close", "fcntl", "dup3",
    "pipe2", "ioctl", "fstat", "sendfile", "splice", "getdents64",
    "openat2", "statx", "pread64",
    # memory
    "mmap", "munmap", "madvise", "mprotect",
    # sockets
    "socket", "socketpair", "bind", "listen", "accept4", "connect",
    "getsockname", "getpeername", "setsockopt", "getsockopt", "shutdown",
    "sendto", "recvfrom", "sendmsg", "recvmsg", "sendmmsg", "recvmmsg",
    # readiness / wakeups
    "ppoll", "epoll_create1", "epoll_ctl", "epoll_pwait", "epoll_pwait2",
    "eventfd2", "futex",
    # io_uring
    "io_uring_setup", "io_uring_enter", "io_uring_register",
]

ARM64_DEFINES = [
    "-D__BITS_PER_LONG=64",
    "-D__ARCH_WANT_RENAMEAT",
    "-D__ARCH_WANT_NEW_STAT",
    "-D__ARCH_WANT_SET_GET_RLIMIT",
    "-D__ARCH_WANT_TIME32_SYSCALLS",
    "-D__ARCH_WANT_SYS_CLONE3",
]


def macros(header: str, extra: list[str]) -> dict[str, int]:
    src = f"#include <{header}>\n"
    out = subprocess.run(
        ["gcc", "-E", "-dM", "-x", "c", "-", *extra],
        input=src, capture_output=True, text=True, check=True,
    ).stdout
    raw: dict[str, str] = {}
    for line in out.splitlines():
        m = re.match(r"#define (__NR\w*) (.+)$", line)
        if m:
            raw[m.group(1)] = m.group(2).strip()

    def resolve(name: str, depth: int = 0) -> int | None:
        if depth > 10 or name not in raw:
            return None
        v = raw[name].strip("() ")
        if re.fullmatch(r"\d+", v):
            return int(v)
        m = re.fullmatch(r"(\w+)\s*\+\s*(\d+)", v)
        if m:
            base = resolve(m.group(1), depth + 1)
            return None if base is None else base + int(m.group(2))
        return resolve(v, depth + 1)

    return {k[len("__NR_"):]: n for k in raw if k.startswith("__NR_")
            if (n := resolve(k)) is not None}


def main() -> int:
    x86 = macros("asm/unistd_64.h", [])
    arm = macros("asm-generic/unistd.h", ARM64_DEFINES)
    missing = [(n, "x86_64" if n not in x86 else "aarch64")
               for n in WANTED if n not in x86 or n not in arm]
    if missing:
        print("missing syscalls:", missing, file=sys.stderr)
        return 1
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    path = os.path.join(root, "src", "linux", "nr.mojo")
    lines = [
        '"""Syscall numbers for x86_64 and aarch64.',
        "",
        "GENERATED by tools/gen_syscall_nr.py from the kernel uapi headers; do not edit.",
        '"""',
        "",
        "from std.sys import CompilationTarget",
        "",
        "comptime _X86 = CompilationTarget.is_x86()",
        "",
    ]
    for n in WANTED:
        lines.append(f"comptime SYS_{n}: Int = {x86[n]} if _X86 else {arm[n]}")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {path} ({len(WANTED)} syscalls)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
